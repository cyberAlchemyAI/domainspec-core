"""Rails Report text artifact POST-gate emission — §4.17.

Blueprint §4 v2.5 §4.17 LOCKED 2026-04-19.
Per-run text document summarizing which rails fired. Non-blocking: failure to
emit does NOT invalidate the run; emits F-RAILS-REPORT-EMISSION-FAIL for next-run
preflight review. Consumes BT13 format (§4.8).
"""

from __future__ import annotations

import json
import os
from dataclasses import dataclass
from typing import Any, Final

BLUEPRINT_DEPS: Final[dict] = {
    "section_04_v2_4_v2_5_amendment.md": {
        "sections_implemented": ["§4.17 rails report POST-gate emission"],
        "hash_source_version": "v2.5",
    },
}

F_RAILS_REPORT_EMISSION_FAIL: Final[str] = "F-RAILS-REPORT-EMISSION-FAIL"

_REPORT_HEADER = (
    "# Tilth Rails Report\n"
    "# Format: BT13 (§4.8)\n"
    "# Generated by pipeline.runtime_integrity._rails_report\n"
    "# NON-BLOCKING: failure to emit does not invalidate the run.\n"
)


@dataclass(frozen=True)
class RailsReportResult:
    """Result of the Rails Report POST-gate emission (§4.17)."""

    emitted: bool
    output_path: str | None
    failure_code: str | None
    detail: dict[str, Any] | None


def emit_rails_report(
    run_id: str,
    gate_events: list[dict[str, Any]],
    output_path: str,
) -> RailsReportResult:
    """Rails Report POST-gate emission (§4.17). [LOCKED §4 v2.5]

    Parameters
    ----------
    run_id : str
        Pipeline run identifier bound at start_run.
    gate_events : list[dict]
        Ordered list of gate event dicts. Each entry should include at minimum:
        {"gate": str, "result": str, "failure_code": str | None, "detail": dict | None}.
    output_path : str
        File path to write the report to. Parent directories are created automatically.
        Canonical path: pipeline/runs/<run_id>/rails_report.md.

    Returns
    -------
    RailsReportResult
        emitted=True on success. emitted=False + failure_code on any I/O error.
        Non-blocking: caller must NOT abort the run on emitted=False.
    """
    try:
        lines = [
            _REPORT_HEADER,
            f"\n## run_id: {run_id}\n",
            f"## gate_events: {len(gate_events)}\n\n",
        ]

        for i, event in enumerate(gate_events, start=1):
            gate = event.get("gate", "UNKNOWN")
            result = event.get("result", "UNKNOWN")
            failure_code = event.get("failure_code")
            detail = event.get("detail")

            lines.append(f"### Event {i}: {gate}\n")
            lines.append(f"- result: {result}\n")
            if failure_code:
                lines.append(f"- failure_code: {failure_code}\n")
            if detail:
                lines.append(f"- detail: {json.dumps(detail, sort_keys=True)}\n")
            lines.append("\n")

        parent = os.path.dirname(output_path)
        if parent:
            os.makedirs(parent, exist_ok=True)

        with open(output_path, "w", encoding="utf-8") as fh:
            fh.writelines(lines)

        return RailsReportResult(
            emitted=True,
            output_path=output_path,
            failure_code=None,
            detail=None,
        )

    except Exception as exc:
        return RailsReportResult(
            emitted=False,
            output_path=None,
            failure_code=F_RAILS_REPORT_EMISSION_FAIL,
            detail={"exception": str(exc), "attempted_path": output_path},
        )
