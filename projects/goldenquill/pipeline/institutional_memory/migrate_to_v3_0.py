"""migrate_to_v3_0.py — mechanical migration of admin_risk_register to v7.0.12 v3.0 shape.

Per architecture v7.0.12 §1.2 (LOCKED 2026-05-16T14:00:00Z) the
``admin_risk_register.yaml`` schema retires ``progressive_register`` and
adds ``per_clc_register`` (a map of CLC slug → AVOID|OK|EXPECTED|PREFERRED,
defaulting to AVOID-everywhere for unmigrated entries).

This script reads the live v2.x register and writes a v3.0 DRAFT side-file
suitable for the operator's per-term audit. The migration is purely
*mechanical schema migration to the architecture-mandated safest default*:

- Field ``progressive_register: <value>`` renamed to
  ``_pre_v7_0_12_progressive_register_PRESERVED_FOR_AUDIT_CONTEXT: <value>``
  (operator-reference field; NEVER read by routing code; per
  ``feedback_no_heuristic_mapping_on_enum_retirement.md`` we preserve the
  prior value as audit context only — we do NOT translate it into a
  per_clc_register default).
- New field ``per_clc_register: {}`` added (empty map = AVOID-everywhere
  per v7.0.12 §1.2 safest default).
- ``version`` bumped to ``3.0``.

The output is a DRAFT side-file at
``admin_risk_register_v3_0_DRAFT_for_audit.yaml``. The operator opens it,
selectively populates per_clc_register based on actual reviewer-vocabulary
analysis (NOT by translating the preserved prior value — per FI-7 REVISED
+ FI-9 REVISED), removes the
``_pre_v7_0_12_progressive_register_PRESERVED_FOR_AUDIT_CONTEXT`` field
once they're done with each term, then renames the file to
``admin_risk_register.yaml`` at cards-ceremony LOCK.

Usage::

    python -m pipeline.institutional_memory.migrate_to_v3_0
    # → writes admin_risk_register_v3_0_DRAFT_for_audit.yaml

The script refuses to overwrite an existing DRAFT file unless ``--force`` is
passed (defends against accidentally clobbering operator audit-in-progress).
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

import yaml


DEFAULT_LIVE_PATH: Path = (
    Path(__file__).parent / "admin_risk_register.yaml"
)
DEFAULT_DRAFT_PATH: Path = (
    Path(__file__).parent / "admin_risk_register_v3_0_DRAFT_for_audit.yaml"
)
PRESERVED_FIELD_NAME: str = (
    "_pre_v7_0_12_progressive_register_PRESERVED_FOR_AUDIT_CONTEXT"
)


HEADER_COMMENT = """# admin_risk_register v3.0 DRAFT — for operator audit
#
# Generated by `python -m pipeline.institutional_memory.migrate_to_v3_0` from the
# live v2.x file. Per architecture v7.0.12 (LOCKED 2026-05-16T14:00:00Z) the
# `progressive_register` field is retired in favor of `per_clc_register` keyed
# by the 8 CapitalLogicCard slugs. The retired value is preserved on each entry
# under `_pre_v7_0_12_progressive_register_PRESERVED_FOR_AUDIT_CONTEXT` for
# operator-audit reference ONLY — it is NEVER read by routing code.
#
# Operator workflow per FI-7 REVISED + FI-9 REVISED (NO heuristic mapping from
# the prior axis):
#   1. For each entry, decide whether AVOID-everywhere (the safest default;
#      empty `per_clc_register: {}` carries this semantics) is correct, OR
#      populate `per_clc_register` with explicit per-CLC values based on actual
#      reviewer-vocabulary analysis.
#   2. Run `python -m pipeline.scripts.audit_term_signer scaffold` to seed the
#      decisions Markdown table (one row per entry).
#   3. Open `admin_risk_register_audit_decisions.md`; fill `audit_status` for
#      each row (`confirmed_avoid_all` if per_clc_register stays empty;
#      `confirmed_per_clc` if you populated it).
#   4. Run `python -m pipeline.scripts.audit_term_signer sign --key <path>` to
#      fill the Ed25519 signature columns.
#   5. Run `python -m pipeline.scripts.audit_term_signer verify` as self-check.
#   6. Delete the `_pre_v7_0_12_progressive_register_PRESERVED_FOR_AUDIT_CONTEXT`
#      field from each entry (or leave it as audit history — the v3.0 schema
#      tolerates additional properties; F-DIALECT-POLITICAL-AXIS-LEAK only
#      rejects entries that still carry the active retired field name).
#   7. Rename this DRAFT file to `admin_risk_register.yaml` (atomic — Phase 2
#      of the two-phase commit per architecture v7.0.12 §1.5b / FI-8 + C2-H-5).
#   8. Re-sign the canonical bytes per BT9 hash-chain discipline.
#   9. Run LOCK ceremony pre-flight; F-DIALECT-MIGRATION-INCOMPLETE accepts.
#
# Authority:
#   - pipeline/architecture/v0.1/architecture_v7_0_12_apolitical_dialect_amendment.md §1.2
#   - pipeline/blueprint/v0.1/section_04_logician_v2_x_apolitical_dialect.md §4.X.6
#   - pipeline/institutional_memory/admin_risk_register.schema.json (v3.0 JSON schema)
#   - feedback memory: feedback_no_heuristic_mapping_on_enum_retirement.md
"""


def migrate(
    raw: dict[str, Any],
    *,
    new_version: str = "3.0",
    new_supersedes: str = (
        "admin_risk_register.yaml v2.3 — schema migrated to v7.0.12 "
        "per architecture amendment LOCKED 2026-05-16T14:00:00Z. Each "
        "entry's `progressive_register` value preserved under "
        "`_pre_v7_0_12_progressive_register_PRESERVED_FOR_AUDIT_CONTEXT` "
        "as operator-audit reference; per-term `per_clc_register` defaults "
        "to empty map (= AVOID-everywhere safest default per §1.2). "
        "Operator audit pending; sign-off via "
        "pipeline/scripts/audit_term_signer.py."
    ),
) -> dict[str, Any]:
    """Apply the mechanical v2.x → v3.0 schema migration to a parsed register."""
    out: dict[str, Any] = dict(raw)
    out["version"] = new_version
    out["supersedes"] = new_supersedes
    entries = raw.get("entries", [])
    if not isinstance(entries, list):
        return out
    migrated_entries: list[dict[str, Any]] = []
    for entry in entries:
        if not isinstance(entry, dict):
            migrated_entries.append(entry)
            continue
        new_entry: dict[str, Any] = {}
        for key, value in entry.items():
            if key == "progressive_register":
                new_entry[PRESERVED_FIELD_NAME] = value
            elif key == "funder_political_axis":
                # Should not appear on admin_risk_register entries, but
                # defend against it.
                new_entry[
                    "_pre_v7_0_12_funder_political_axis_PRESERVED_FOR_AUDIT_CONTEXT"
                ] = value
            else:
                new_entry[key] = value
        # Add the new field if not present.
        if "per_clc_register" not in new_entry:
            new_entry["per_clc_register"] = {}
        migrated_entries.append(new_entry)
    out["entries"] = migrated_entries
    return out


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(
        prog="migrate_to_v3_0",
        description=(
            "Mechanically migrate admin_risk_register.yaml from v2.x → v3.0 "
            "(safest default; operator audit follows). Per architecture "
            "v7.0.12 §1.2."
        ),
    )
    p.add_argument(
        "--live",
        help="Path to live admin_risk_register.yaml (default: live path)",
    )
    p.add_argument(
        "--draft",
        help=(
            "Output path for v3.0 DRAFT side-file "
            "(default: admin_risk_register_v3_0_DRAFT_for_audit.yaml)"
        ),
    )
    p.add_argument(
        "--force", action="store_true", help="Overwrite existing DRAFT file"
    )
    args = p.parse_args(list(argv) if argv is not None else None)
    live_path = Path(args.live or DEFAULT_LIVE_PATH)
    draft_path = Path(args.draft or DEFAULT_DRAFT_PATH)
    if draft_path.exists() and not args.force:
        print(
            f"error: {draft_path} already exists; pass --force to overwrite",
            file=sys.stderr,
        )
        return 2
    raw = yaml.safe_load(live_path.read_text(encoding="utf-8"))
    if not isinstance(raw, dict):
        print(f"error: {live_path} does not parse to a dict", file=sys.stderr)
        return 2
    migrated = migrate(raw)
    draft_path.write_text(
        HEADER_COMMENT
        + "\n"
        + yaml.safe_dump(
            migrated,
            sort_keys=False,
            default_flow_style=False,
            allow_unicode=True,
        ),
        encoding="utf-8",
    )
    entries = migrated.get("entries", [])
    print(
        f"wrote v3.0 DRAFT for {len(entries)} entries to {draft_path}",
        file=sys.stderr,
    )
    return 0


if __name__ == "__main__":  # pragma: no cover - thin wrapper
    raise SystemExit(main())
