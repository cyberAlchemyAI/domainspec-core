function matches(source, expression) {
  return [...source.matchAll(expression)].map((match) => match[1]);
}

test("exact relation arrow keeps source predicate and target in semantic HTML", () => {
  const html = renderRelationArrow({
    relation: {
      relation_id: "body-war.relation.example",
      predicate: "projects",
      authority_effect: "projection",
    },
    source: {
      concept_id: "body-war.business.operation.source",
      label: "Source operation",
    },
    target: {
      concept_id: "body-war.business.outcome.target",
      label: "Target outcome",
    },
    phrase: "shows a limited view of",
    portal: true,
  });

  assert.match(html, /class="relation-arrow relation-effect-projection relation-arrow--portal"/);
  assert.match(html, /data-arrow-relation-id="body-war\.relation\.example"/);
  assert.match(html, /aria-hidden="true" focusable="false"/);
  assert.match(html, />Source operation<\/strong><\/a>/);
  assert.match(html, /<code>projects<\/code>/);
  assert.match(html, /shows a limited view of/);
  assert.match(html, />Target outcome<\/strong><\/a>/);
});

