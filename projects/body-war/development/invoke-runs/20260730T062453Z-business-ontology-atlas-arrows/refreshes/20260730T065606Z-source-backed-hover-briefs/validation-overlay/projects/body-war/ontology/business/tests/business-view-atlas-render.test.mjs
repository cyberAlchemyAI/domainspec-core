test("every ordinary atlas fragment resolves to exactly one static DOM target", async () => {
  const html = await readFile(
    path.join(packageRoot, "BUSINESS-VIEW-ATLAS.html"),
    "utf8",
  );
  const ids = matches(html, /\sid="([^"]+)"/g);
  const idCounts = new Map();
  for (const id of ids) idCounts.set(id, (idCounts.get(id) ?? 0) + 1);
  for (const [id, count] of idCounts) {
    assert.equal(count, 1, `duplicate DOM id: ${id}`);
  }
  const fragments = matches(html, /href="#([^"]+)"/g);
  assert.ok(fragments.length > 500);
  for (const fragment of fragments) {
    assert.equal(idCounts.get(fragment), 1, `missing fragment target: ${fragment}`);
  }
});

test("atlas is static-first and JavaScript is progressive enhancement", async () => {
  const html = await readFile(
    path.join(packageRoot, "BUSINESS-VIEW-ATLAS.html"),
    "utf8",
  );
  assert.match(html, /<nav class="lens-nav"/);
  assert.match(html, /<main id="atlas-main"/);
  assert.match(html, /<details><summary>Exact node metadata<\/summary>/);
  assert.match(html, /<details><summary>Exact relation metadata<\/summary>/);
  assert.match(html, /document\.documentElement\.classList\.add\('js'\)/);
  assert.match(html, /@media\(prefers-reduced-motion:reduce\)/);
  assert.match(html, /@media print/);
  assert.match(html, /@media\(max-width:600px\)/);
  assert.match(html, /role="status" aria-live="polite"/);
  assert.match(html, /class="skip-link"/);
});

