import assert from "node:assert/strict";
import { execFile } from "node:child_process";
import { readFile } from "node:fs/promises";
import path from "node:path";
import test from "node:test";
import { promisify } from "node:util";
import { fileURLToPath } from "node:url";

const execFileAsync = promisify(execFile);
const packageRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);

function matches(source, expression) {
  return [...source.matchAll(expression)].map((match) => match[1]);
}

test("whole-ontology atlas generated bytes are current", async () => {
  const { stdout } = await execFileAsync(
    process.execPath,
    [path.join(packageRoot, "scripts/generate-views.mjs"), "--check"],
    { cwd: path.resolve(packageRoot, "../../../..") },
  );
  assert.match(stdout, /and 3 HTML projections/);
});

test("atlas renders six lenses, seventeen kinds, every node, and every relation once", async () => {
  const html = await readFile(
    path.join(packageRoot, "BUSINESS-VIEW-ATLAS.html"),
    "utf8",
  );
  const conceptIds = matches(html, /data-concept-id="([^"]+)"/g);
  const relationIds = matches(html, /data-relation-id="([^"]+)"/g);
  const lensIds = matches(html, /data-lens-id="([^"]+)"/g);
  const kindHeadings = matches(
    html,
    /<h3 id="kind-[^"]+">([^ <]+) <span>/g,
  );

  assert.equal(lensIds.length, 6);
  assert.equal(new Set(lensIds).size, 6);
  assert.equal(kindHeadings.length, 17);
  assert.equal(new Set(kindHeadings).size, 17);
  assert.equal(conceptIds.length, 237);
  assert.equal(new Set(conceptIds).size, 237);
  assert.equal(relationIds.length, 231);
  assert.equal(new Set(relationIds).size, 231);
});

